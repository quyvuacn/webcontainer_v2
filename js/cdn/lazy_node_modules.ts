/**
 * Lazy on-demand CDN fetcher for node_modules files.
 *
 * When any worker tries to read a node_modules file that isn't in the VFS,
 * we resolve its version from the installed stub and fetch it from unpkg.com.
 * The result is cached in the VFS so subsequent reads are instant.
 */

import { CDN_BASE } from './config'

/** Parse a VFS path into package root, package name, and file path.
 *  Handles both scoped (@scope/name) and plain (name) packages.
 *  Returns null if the path is not under a node_modules directory. */
export function parseNodeModulesPath(
  vfsPath: string,
): { pkgRoot: string; pkgName: string; filePath: string } | null {
  // e.g. ~/projects/node_modules/vite/dist/client/client.mjs
  //      ~/projects/node_modules/@types/node/index.d.ts
  const m = vfsPath.match(/^(.*?node_modules\/)(@[^/]+\/[^/]+|[^/]+)\/(.+)$/)
  if (!m) return null
  return { pkgRoot: m[1] + m[2], pkgName: m[2], filePath: m[3] }
}

/**
 * Fetch a node_modules file from CDN on demand.
 * Caches the result in the VFS for future reads.
 * Strips shebangs from bin/ JS files automatically.
 */
export async function lazyFetchNodeModulesFile(
  vfsPath: string,
  vfsRead:  (p: string) => Uint8Array | null,
  vfsWrite: (p: string, b: Uint8Array) => void,
): Promise<Uint8Array | null> {
  const parsed = parseNodeModulesPath(vfsPath)
  if (!parsed) return null

  // Resolve version from installed stub
  const stubBytes = vfsRead(`${parsed.pkgRoot}/package.json`)
  if (!stubBytes) return null

  let version: string
  try {
    version = JSON.parse(new TextDecoder().decode(stubBytes)).version
    if (!version) return null
  } catch { return null }

  try {
    const url = `${CDN_BASE}/${parsed.pkgName}@${version}/${parsed.filePath}`
    const res = await fetch(url)
    if (!res.ok) return null

    let bytes = new Uint8Array(await res.arrayBuffer())

    // Strip shebang for executable scripts in bin/
    if (parsed.filePath.startsWith('bin/') && (parsed.filePath.endsWith('.js') || parsed.filePath.endsWith('.mjs'))) {
      const text = new TextDecoder().decode(bytes)
      if (text.startsWith('#!')) {
        const stripped = text.slice(text.indexOf('\n') + 1)
        bytes = new TextEncoder().encode(stripped)
      }
    }

    vfsWrite(vfsPath, bytes)
    return bytes
  } catch { return null }
}

/**
 * Check whether a node_modules file exists on CDN (uses HEAD to avoid downloading).
 * Does NOT cache — use lazyFetchNodeModulesFile to cache on positive results.
 */
export async function lazyExistsNodeModulesFile(
  vfsPath: string,
  vfsRead: (p: string) => Uint8Array | null,
): Promise<boolean> {
  const parsed = parseNodeModulesPath(vfsPath)
  if (!parsed) return false

  const stubBytes = vfsRead(`${parsed.pkgRoot}/package.json`)
  if (!stubBytes) return false

  let version: string
  try {
    version = JSON.parse(new TextDecoder().decode(stubBytes)).version
    if (!version) return false
  } catch { return false }

  try {
    const url = `${CDN_BASE}/${parsed.pkgName}@${version}/${parsed.filePath}`
    const res = await fetch(url, { method: 'HEAD' })
    return res.ok
  } catch { return false }
}
