import { CDN_BASE } from "./config";

// ─── Conditions ───────────────────────────────────────────────────────

const CONDITIONS = ["browser", "import", "module", "default"];

// ─── Utils ────────────────────────────────────────────────────────────

function parseNodeModulesPath(vfsPath: string) {
  // Dùng LAST occurrence của "node_modules/" để lấy đúng package đang được resolve.
  // Nếu dùng FIRST, path như "project/node_modules/vite/dist/node/node_modules/picomatch"
  // sẽ bị parse thành pkgRoot=vite và filePath=dist/node/node_modules/picomatch,
  // dẫn đến CDN fetch sai (vite@x.y.z/dist/node/node_modules/picomatch không tồn tại).
  const lastIdx = vfsPath.lastIndexOf("/node_modules/");
  if (lastIdx < 0) return null;

  const prefix = vfsPath.slice(0, lastIdx + "/node_modules/".length);
  const rest = vfsPath.slice(prefix.length);

  const m = rest.match(/^(@[^/]+\/[^/]+|[^/]+)\/?(.*)$/);
  if (!m) return null;

  return {
    pkgRoot: prefix + m[1],
    pkgName: m[1],
    filePath: m[2] || "",
  };
}

function readJSON(vfsRead: any, p: string) {
  const b = vfsRead(p);
  if (!b) return null;
  try {
    return JSON.parse(new TextDecoder().decode(b));
  } catch {
    return null;
  }
}

// ─── Entry resolution ─────────────────────────────────────────────────

function resolveEntry(pkg: any) {
  if (pkg.exports) {
    const r = resolveExports(pkg.exports, ".", CONDITIONS);
    if (typeof r === "string") return r;
  }

  if (pkg.module) return pkg.module;
  if (pkg.main) return pkg.main;

  return "index.js";
}

// ─── Exports resolver (simplified but usable) ─────────────────────────

function resolveExports(
  exports: any,
  subpath: string,
  conditions: string[],
): string | null | undefined {
  if (typeof exports === "string") return exports;
  if (exports === null) return null;

  if (Array.isArray(exports)) {
    for (const e of exports) {
      const r = resolveExports(e, subpath, conditions);
      if (r !== undefined) return r;
    }
    return;
  }

  if (typeof exports === "object") {
    const keys = Object.keys(exports);

    // path map
    if (keys.some((k) => k.startsWith(".") || k.includes("*"))) {
      if (subpath in exports) {
        return resolveExports(exports[subpath], subpath, conditions);
      }

      for (const k of keys) {
        if (!k.includes("*")) continue;
        const [base] = k.split("*");
        if (subpath.startsWith(base)) {
          const r = resolveExports(exports[k], subpath, conditions);
          if (typeof r === "string") {
            return r.replace("*", subpath.slice(base.length));
          }
        }
      }
    }

    // condition map
    for (const c of conditions) {
      if (c in exports) {
        const r = resolveExports(exports[c], subpath, conditions);
        if (r !== undefined) return r;
      }
    }
  }
}

// ─── Extension resolution ─────────────────────────────────────────────

function tryExtensions(
  base: string,
  vfsRead: (p: string) => Uint8Array | null,
) {
  const list = [
    base,
    base + ".js",
    base + ".mjs",
    base + ".cjs",
    base + "/index.js",
    base + "/index.mjs",
  ];

  for (const p of list) {
    if (vfsRead(p)) return p;
  }

  return base;
}

// ─── Import rewrite (VERY IMPORTANT) ──────────────────────────────────

function rewriteImports(code: string, versionMap: Record<string, string>) {
  return code.replace(/from\s+['"]([^'"]+)['"]/g, (_, spec) => {
    if (spec.startsWith(".") || spec.startsWith("/")) return `from "${spec}"`;

    const v = versionMap[spec];
    if (!v) return `from "${spec}"`;

    return `from "/${spec}@${v}/index.js"`;
  });
}

// ─── Main fetch ───────────────────────────────────────────────────────

export async function lazyFetchNodeModulesFile(
  vfsPath: string,
  vfsRead: (p: string) => Uint8Array | null,
  vfsWrite: (p: string, b: Uint8Array) => void,
  versionMap: Record<string, string> = {},
): Promise<Uint8Array | null> {
  const parsed = parseNodeModulesPath(vfsPath);
  if (!parsed) return null;

  const pkg = readJSON(vfsRead, `${parsed.pkgRoot}/package.json`);
  if (!pkg?.version) return null;

  let filePath = parsed.filePath;

  if (!filePath) {
    filePath = resolveEntry(pkg);
  } else if (pkg.exports) {
    const sub = "./" + filePath;
    const r = resolveExports(pkg.exports, sub, CONDITIONS);
    // r === null  → subpath is explicitly blocked in exports map → deny access
    // r === undefined → subpath not listed in exports map (e.g. internal chunk
    //   files like vite/dist/node/chunks/dep-BK3b2jBa.js) → fall through and
    //   fetch filePath directly from CDN
    if (r === null) return null;
    if (typeof r === "string") filePath = r.replace(/^\.\//, "");
    // r === undefined: keep original filePath, fetch directly
  }

  filePath = tryExtensions(`${parsed.pkgRoot}/${filePath}`, vfsRead).replace(
    parsed.pkgRoot + "/",
    "",
  );

  const url = `${CDN_BASE}/${parsed.pkgName}@${pkg.version}/${filePath}`;

  try {
    const res = await fetch(url);
    if (!res.ok) return null;

    let text = await res.text();

    // strip shebang
    if (text.startsWith("#!")) {
      text = text.slice(text.indexOf("\n") + 1);
    }

    text = rewriteImports(text, versionMap);

    const bytes = new TextEncoder().encode(text);
    vfsWrite(vfsPath, bytes);

    return bytes;
  } catch {
    return null;
  }
}
