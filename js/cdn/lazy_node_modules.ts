/**
 * Lazy on-demand CDN fetcher for node_modules files.
 *
 * Supports the full Node.js package resolution algorithm:
 *   - "exports" field: conditional exports, wildcard patterns, null blocking
 *   - "imports" field: internal package aliases (#specifier)
 *   - "typesVersions" is intentionally ignored (runtime only)
 *   - Falls back to direct path when no "exports" field present
 */

import { CDN_BASE } from "./config";

// ─── Types ────────────────────────────────────────────────────────────────────

type ExportsValue = string | null | ExportsObject | ExportsValue[];

interface ExportsObject {
  [key: string]: ExportsValue;
}

interface ParsedNodeModulesPath {
  pkgRoot: string; // e.g. "project/node_modules/@vitejs/plugin-react"
  pkgName: string; // e.g. "@vitejs/plugin-react"
  filePath: string; // e.g. "dist/client/client.mjs"
}

// Conditions used to resolve conditional exports.
// Order matters — first match wins, matching Node's algorithm.
const DEFAULT_CONDITIONS_ESM = ["import", "module-sync", "default"];
const DEFAULT_CONDITIONS_CJS = ["require", "default"];

// ─── Path parsing ─────────────────────────────────────────────────────────────

/**
 * Parse a VFS path into package root, package name, and file path.
 * Handles both scoped (@scope/name) and plain (name) packages.
 * Returns null for paths not under node_modules, or paths where filePath
 * itself contains node_modules (nested resolution — let the resolver walk up).
 */
export function parseNodeModulesPath(
  vfsPath: string,
): ParsedNodeModulesPath | null {
  const m = vfsPath.match(/^(.*?node_modules\/)(@[^/]+\/[^/]+|[^/]+)\/(.+)$/);
  if (!m) return null;

  const filePath = m[3];
  if (filePath.includes("node_modules")) return null;

  return { pkgRoot: m[1] + m[2], pkgName: m[2], filePath };
}

// ─── Package.json reading ─────────────────────────────────────────────────────

interface PackageJson {
  version?: string;
  exports?: ExportsValue;
  imports?: Record<string, ExportsValue>;
  main?: string;
  module?: string;
}

function readPackageJson(
  pkgRoot: string,
  vfsRead: (p: string) => Uint8Array | null,
): PackageJson | null {
  const bytes = vfsRead(`${pkgRoot}/package.json`);
  if (!bytes) return null;
  try {
    return JSON.parse(new TextDecoder().decode(bytes)) as PackageJson;
  } catch {
    return null;
  }
}

// ─── Exports resolution ───────────────────────────────────────────────────────

/**
 * Resolve a package subpath (e.g. "." or "./client") against an exports map,
 * using the given condition set. Returns the resolved relative path string,
 * null (explicitly blocked), or undefined (no match found).
 *
 * Implements PACKAGE_EXPORTS_RESOLVE as per Node.js docs:
 *   https://nodejs.org/api/esm.html#resolver-algorithm-specification
 */
function resolveExports(
  exports: ExportsValue,
  subpath: string,
  conditions: string[],
): string | null | undefined {
  // String shorthand: { ".": "./dist/index.js" } or top-level string
  if (typeof exports === "string") {
    return exports;
  }

  // Explicit null block
  if (exports === null) {
    return null;
  }

  // Array: try each entry in order, return first non-undefined match
  if (Array.isArray(exports)) {
    for (const entry of exports) {
      const result = resolveExports(entry, subpath, conditions);
      if (result !== undefined) return result;
    }
    return undefined;
  }

  // Object: could be condition map OR path map — distinguished by key prefix
  if (typeof exports === "object") {
    const keys = Object.keys(exports);
    if (keys.length === 0) return undefined;

    const firstKey = keys[0];
    const isPathMap =
      firstKey === "." || firstKey.startsWith("./") || firstKey.includes("*");

    if (isPathMap) {
      // Path map: find matching subpath key (exact or wildcard)
      return resolvePathMap(
        exports as Record<string, ExportsValue>,
        subpath,
        conditions,
      );
    } else {
      // Condition map: find first matching condition
      return resolveConditionMap(
        exports as Record<string, ExportsValue>,
        conditions,
      );
    }
  }

  return undefined;
}

/**
 * Resolve against a path map: { "./foo": ..., "./bar/*": ..., ".": ... }
 */
function resolvePathMap(
  pathMap: Record<string, ExportsValue>,
  subpath: string,
  conditions: string[],
): string | null | undefined {
  // 1. Exact match
  if (subpath in pathMap) {
    return resolveExports(pathMap[subpath], subpath, conditions);
  }

  // 2. Wildcard pattern match (longest pattern wins)
  let bestPatternMatch: string | undefined;
  let bestKey: string | undefined;

  for (const key of Object.keys(pathMap)) {
    if (!key.includes("*")) continue;

    const [patternBase, patternTrailer] = key.split("*", 2) as [string, string];
    if (!subpath.startsWith(patternBase)) continue;
    if (patternTrailer !== undefined && !subpath.endsWith(patternTrailer))
      continue;

    // Pattern matches; prefer the longest (most specific) base
    if (!bestKey || patternBase.length > (bestKey.split("*")[0]?.length ?? 0)) {
      bestKey = key;
      bestPatternMatch = subpath.slice(
        patternBase.length,
        patternTrailer ? subpath.length - patternTrailer.length : undefined,
      );
    }
  }

  if (bestKey !== undefined && bestPatternMatch !== undefined) {
    const mappedValue = pathMap[bestKey];
    const resolved = resolveExports(mappedValue, subpath, conditions);
    if (typeof resolved === "string") {
      return resolved.replaceAll("*", bestPatternMatch);
    }
    return resolved;
  }

  return undefined;
}

/**
 * Resolve against a condition map: { "import": ..., "require": ..., "default": ... }
 * Iterates keys in declaration order; returns first matching condition's value.
 */
function resolveConditionMap(
  condMap: Record<string, ExportsValue>,
  conditions: string[],
): string | null | undefined {
  for (const key of Object.keys(condMap)) {
    if (conditions.includes(key)) {
      const result = resolveExports(condMap[key], ".", conditions);
      if (result !== undefined) return result;
    }
  }
  return undefined;
}

/**
 * Given a package root and an import specifier (e.g. "vite/client" → subpath "./client"),
 * resolve the actual file path using the package's "exports" field.
 *
 * Returns:
 *   { resolved: string }   — resolved relative path (strip leading "./" to get filePath)
 *   { blocked: true }      — explicitly null-blocked by exports
 *   null                   — no exports field, or no match (fall through to direct path)
 */
export function resolvePackageExports(
  pkg: PackageJson,
  subpath: string, // "." | "./client" | "./dist/client/foo.js"
  conditions = DEFAULT_CONDITIONS_ESM,
): { resolved: string } | { blocked: true } | null {
  if (!pkg.exports) return null;

  const result = resolveExports(pkg.exports, subpath, conditions);

  if (result === undefined) return null;
  if (result === null) return { blocked: true };
  return { resolved: result };
}

/**
 * Resolve an internal "#imports" alias (e.g. "#module-sync-enabled").
 * These are only valid within the package itself.
 */
export function resolvePackageImports(
  pkg: PackageJson,
  specifier: string, // starts with "#"
  conditions = DEFAULT_CONDITIONS_ESM,
): { resolved: string } | { blocked: true } | null {
  if (!pkg.imports) return null;

  const result = resolveExports(
    pkg.imports as ExportsObject,
    specifier,
    conditions,
  );

  if (result === undefined) return null;
  if (result === null) return { blocked: true };
  return { resolved: result };
}

// ─── VFS path → CDN URL ───────────────────────────────────────────────────────

/**
 * Given a parsed node_modules path and the package.json content,
 * compute the CDN file path respecting the "exports" field.
 *
 * filePath in ParsedNodeModulesPath is relative to pkgRoot (no leading "./").
 * subpath is the import specifier relative to the package root:
 *   - "dist/client/client.mjs" → "./dist/client/client.mjs"
 *   - "" → "."
 */
function computeCdnFilePath(
  parsed: ParsedNodeModulesPath,
  pkg: PackageJson,
  conditions: string[],
): string | null {
  const { filePath } = parsed;

  // Direct file access (e.g. import from "pkg/dist/client/foo.mjs")
  // → subpath is "./dist/client/foo.mjs"
  const subpath = filePath ? `./${filePath}` : ".";

  // Internal imports alias (#specifier) — only if this is an internal call
  if (subpath.startsWith("#")) {
    const result = resolvePackageImports(pkg, subpath, conditions);
    if (!result) return filePath; // no match, try direct
    if ("blocked" in result) return null;
    return result.resolved.replace(/^\.\//, "");
  }

  const result = resolvePackageExports(pkg, subpath, conditions);

  if (result === null) {
    // No "exports" field or no match → use direct path
    return filePath;
  }

  if ("blocked" in result) {
    // Explicitly blocked by null entry
    return null;
  }

  // Strip leading "./"
  return result.resolved.replace(/^\.\//, "");
}

// ─── Public API ───────────────────────────────────────────────────────────────

/**
 * Fetch a node_modules file from CDN on demand.
 * Caches the result in the VFS for future reads.
 * Respects "exports" field for correct path resolution.
 * Strips shebangs from bin/ JS files automatically.
 */
export async function lazyFetchNodeModulesFile(
  vfsPath: string,
  vfsRead: (p: string) => Uint8Array | null,
  vfsWrite: (p: string, b: Uint8Array) => void,
  conditions = DEFAULT_CONDITIONS_ESM,
): Promise<Uint8Array | null> {
  const parsed = parseNodeModulesPath(vfsPath);
  if (!parsed) return null;

  const pkg = readPackageJson(parsed.pkgRoot, vfsRead);
  if (!pkg?.version) return null;

  const cdnFilePath = computeCdnFilePath(parsed, pkg, conditions);
  if (cdnFilePath === null) return null; // blocked by null exports entry

  try {
    const url = `${CDN_BASE}/${parsed.pkgName}@${pkg.version}/${cdnFilePath}`;
    const res = await fetch(url);
    if (!res.ok) return null;

    let bytes = new Uint8Array(await res.arrayBuffer());

    // Strip shebang from bin/ executables
    if (
      parsed.filePath.startsWith("bin/") &&
      (parsed.filePath.endsWith(".js") || parsed.filePath.endsWith(".mjs"))
    ) {
      const text = new TextDecoder().decode(bytes);
      if (text.startsWith("#!")) {
        bytes = new TextEncoder().encode(text.slice(text.indexOf("\n") + 1));
      }
    }

    // Cache under the ORIGINAL vfsPath, not the resolved one.
    // The resolver already mapped the path; VFS lookups will use the original key.
    vfsWrite(vfsPath, bytes);
    return bytes;
  } catch {
    return null;
  }
}

/**
 * Check whether a node_modules file exists on CDN (HEAD request, no download).
 * Respects "exports" field. Does NOT cache — use lazyFetchNodeModulesFile for that.
 */
export async function lazyExistsNodeModulesFile(
  vfsPath: string,
  vfsRead: (p: string) => Uint8Array | null,
  conditions = DEFAULT_CONDITIONS_ESM,
): Promise<boolean> {
  const parsed = parseNodeModulesPath(vfsPath);
  if (!parsed) return false;

  const pkg = readPackageJson(parsed.pkgRoot, vfsRead);
  if (!pkg?.version) return false;

  const cdnFilePath = computeCdnFilePath(parsed, pkg, conditions);
  if (cdnFilePath === null) return false; // explicitly blocked

  try {
    const url = `${CDN_BASE}/${parsed.pkgName}@${pkg.version}/${cdnFilePath}`;
    const res = await fetch(url, { method: "HEAD" });
    return res.ok;
  } catch {
    return false;
  }
}
